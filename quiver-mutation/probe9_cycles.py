#!/usr/bin/env python3
"""Probe 9 (Danielle directions 6 + 2): is the leaky rank-5 family INERT, and is
its orbit graph generated by squares (4-cycles) and pentagons (5-cycles)?

Exp A (distortion / inertness): for several counter values c, enumerate the
entry-capped orbit component of T(c) and report |V|, |E|, cycle-space dim
(E-V+1), and BFS eccentricity. If these are ~c-independent, the family is inert
(c is a passive label, no computation) -- consistent with the finite descent
core, and it means the self-corruption is neither "garbage that won't uncompute"
(dir 1) nor "unintended long cycles" (dir 2) but simply no computation.

Exp B (cycle basis): on one component, compute the fundamental-cycle-length
distribution from a BFS spanning tree (each non-tree edge -> one cycle, length
via LCA). Girth and the short-cycle share tell us whether the cycle space is
square/pentagon-generated (cluster-like) or has independent long cycles
(instruction material for dir 2).
"""
import sys
from collections import deque

N=5
IDX={}; PAIRS=[]
for i in range(N):
    for j in range(i+1,N): IDX[(i,j)]=len(PAIRS); PAIRS.append((i,j))
def mutate(t,k):
    B=[[0]*N for _ in range(N)]
    for (i,j),v in zip(PAIRS,t): B[i][j]=v; B[j][i]=-v
    Bp=[[0]*N for _ in range(N)]
    for i in range(N):
        for j in range(N):
            if i==k or j==k: Bp[i][j]=-B[i][j]
            else: Bp[i][j]=B[i][j]+(abs(B[i][k])*B[k][j]+B[i][k]*abs(B[k][j]))//2
    return tuple(Bp[i][j] for (i,j) in PAIRS)
def seed(c):
    e={(0,1):1,(1,2):1,(0,2):c,(0,3):1,(1,3):2,(1,4):2,(2,4):-1}
    return tuple(e.get(p,0) for p in PAIRS)
def maxabs(t): return max(abs(x) for x in t)

def component(c, cap, statecap=200000):
    s=seed(c); seen={s:0}; q=deque([s]); order=[s]
    while q:
        t=q.popleft()
        for k in range(N):
            u=mutate(t,k)
            if maxabs(u)>cap or u in seen: continue
            if len(seen)>=statecap: return seen,order,True
            seen[u]=len(order); order.append(u); q.append(u)
    return seen,order,False

def graph_stats(c, cap):
    seen,order,cut=component(c,cap)
    V=len(order); idx=seen
    # internal undirected edges
    edges=set()
    for t in order:
        for k in range(N):
            u=mutate(t,k)
            if u in idx:
                a,b=idx[t],idx[u]
                edges.add((a,b) if a<b else (b,a))
    E=len(edges)
    # BFS tree from seed for eccentricity + fundamental cycles
    adj=[[] for _ in range(V)]
    for a,b in edges: adj[a].append(b); adj[b].append(a)
    depth=[-1]*V; par=[-1]*V; depth[0]=0; q=deque([0]); ecc=0
    while q:
        x=q.popleft(); ecc=max(ecc,depth[x])
        for y in adj[x]:
            if depth[y]<0: depth[y]=depth[x]+1; par[y]=x; q.append(y)
    return V,E,E-V+1,ecc,cut,depth,par,edges

def lca_len(u,v,depth,par):
    # length of fundamental cycle for non-tree edge (u,v)
    a,b=u,v; d=1
    while depth[a]>depth[b]: a=par[a]; d+=1
    while depth[b]>depth[a]: b=par[b]; d+=1
    while a!=b: a=par[a]; b=par[b]; d+=2
    return d

if __name__=="__main__":
    print("=== Exp A: inertness (component vs counter value c), cap=20 ===")
    for c in (4,5,6,8,10,14,20):
        V,E,cyc,ecc,cut,_,_,_=graph_stats(c,20)
        print(f"  c={c:2d}: |V|={V:6d} |E|={E:6d} cycle-dim(E-V+1)={cyc:6d} "
              f"BFS-eccentricity={ecc}{'  [cut]' if cut else ''}")

    print("\n=== Exp B: cycle basis of T(5) component, cap=16 ===")
    V,E,cyc,ecc,cut,depth,par,edges=graph_stats(5,16)
    print(f"  |V|={V} |E|={E} cycle-dim={cyc} eccentricity={ecc}{'  [cut]' if cut else ''}")
    # fundamental cycle length distribution
    tree_edges=set()
    for v in range(V):
        if par[v]>=0:
            a,b=v,par[v]; tree_edges.add((a,b) if a<b else (b,a))
    from collections import Counter
    dist=Counter()
    for a,b in edges:
        if (a,b) in tree_edges: continue
        dist[lca_len(a,b,depth,par)]+=1
    print("  fundamental-cycle-length distribution:")
    for L in sorted(dist):
        print(f"    length {L:2d}: {dist[L]}")
    short=sum(n for L,n in dist.items() if L<=5)
    tot=sum(dist.values())
    print(f"  girth(min fundamental cycle) = {min(dist)}; "
          f"short(<=5)/total fundamental cycles = {short}/{tot} = {short/tot:.3f}")
    print("  (all/most short => square+pentagon-generated (cluster-like, inert); "
          "long cycles => independent instruction material)")
